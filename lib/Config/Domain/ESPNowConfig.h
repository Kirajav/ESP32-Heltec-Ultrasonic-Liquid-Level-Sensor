#ifndef ESPNOW_CONFIG_H
#define ESPNOW_CONFIG_H

#include <Arduino.h>
#include <ArduinoJson.h>
#include <vector>

// Modo de ESP-NOW (3.5.0): ya no se enciende siempre, porque con ESP-NOW
// activo y rol receptor la radio no puede dormir (0.12 A en vez de 0.059 A)
enum EspNowMode : uint8_t {
    ESPNOW_MODE_OFF = 0,     // Apagado: ESP-NOW nunca se inicializa
    ESPNOW_MODE_MANUAL = 1,  // Manual: siempre encendido
    ESPNOW_MODE_AUTO = 2     // Automático: solo cuando falta el WiFi unos minutos
};

// Rol según la asimetría de la radio: enviar funciona con modem sleep,
// recibir no. Solo el receptor mantiene la radio despierta
enum EspNowRole : uint8_t {
    ESPNOW_ROLE_EMISOR = 0,    // Solo transmite su lectura (p. ej. la azotea)
    ESPNOW_ROLE_RECEPTOR = 1   // Recibe y muestra/publica los tinacos remotos
};

// Unidad emparejada con la clave (persistida en /config.json)
struct EspNowPairedPeer {
    uint8_t mac[6];
    String name;
    EspNowRole role;
};

/**
 * ESP-NOW Configuration Management
 * Modo, rol, clave de emparejamiento, último canal y unidades emparejadas
 */
class ESPNowConfig {
public:
    static const size_t MAX_PEERS = 4;
    static const size_t KEY_MIN_LEN = 8;
    static const size_t KEY_MAX_LEN = 64;

private:
    // Auto-generated device identity
    String deviceMAC;
    String deviceChipID;
    uint8_t autoSensorID;
    String autoSensorName;

    // User configurable
    EspNowMode mode;
    EspNowRole role;
    String pairingKey;       // Nunca se devuelve por la API (como la contraseña MQTT)
    uint8_t lastChannel;     // Canal del router; respaldo sin WiFi (0 = desconocido)
    std::vector<EspNowPairedPeer> peers;
    String customSensorName;
    uint8_t customSensorID;
    bool useAutoID;
    bool useAutoName;

    void generateAutoIdentity();

public:
    ESPNowConfig();

    // Initialization
    void initialize();

    // Modo y rol
    EspNowMode getMode() const { return mode; }
    void setMode(EspNowMode m) { mode = m; }
    EspNowRole getRole() const { return role; }
    void setRole(EspNowRole r) { role = r; }
    bool isReceptor() const { return role == ESPNOW_ROLE_RECEPTOR; }
    static const char* modeToString(EspNowMode m);
    static bool modeFromString(const String& s, EspNowMode& out);
    static const char* roleToString(EspNowRole r);
    static bool roleFromString(const String& s, EspNowRole& out);

    // Clave de emparejamiento
    bool hasPairingKey() const { return pairingKey.length() >= KEY_MIN_LEN; }
    const String& getPairingKey() const { return pairingKey; }
    bool setPairingKey(const String& key);  // false si la longitud no es válida

    // Último canal conocido del router
    uint8_t getLastChannel() const { return lastChannel; }
    void setLastChannel(uint8_t ch) { if (ch >= 1 && ch <= 13) lastChannel = ch; }

    // Unidades emparejadas
    const std::vector<EspNowPairedPeer>& getPeers() const { return peers; }
    bool hasPeers() const { return !peers.empty(); }
    // Agrega o actualiza; false si no cabe. 'changed' indica si hay que guardar
    bool upsertPeer(const uint8_t* mac, const String& name, EspNowRole role, bool& changed);
    bool removePeer(const uint8_t* mac);
    void clearPeers() { peers.clear(); }

    // Identity management
    uint8_t getSensorID() const;
    String getSensorName() const;
    void setCustomSensorID(uint8_t id);
    void setCustomSensorName(const String& name);
    void useAutoGeneratedID(bool use) { useAutoID = use; }
    void useAutoGeneratedName(bool use) { useAutoName = use; }

    // Device info (read-only)
    String getDeviceMAC() const { return deviceMAC; }
    String getDeviceChipID() const { return deviceChipID; }
    uint8_t getAutoSensorID() const { return autoSensorID; }
    String getAutoSensorName() const { return autoSensorName; }

    // JSON serialization
    void toJson(JsonObject& json) const;
    void fromJson(const JsonObject& json);
};

#endif // ESPNOW_CONFIG_H
